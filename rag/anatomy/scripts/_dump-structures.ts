import { MUSCLES } from '../../../src/data/fitness/anatomy/muscles';
import { TENDONS } from '../../../src/data/fitness/anatomy/tendons';
import { NERVES } from '../../../src/data/fitness/anatomy/nerves';
import { JOINTS } from '../../../src/data/fitness/anatomy/joints';
import { BONES } from '../../../src/data/fitness/anatomy/bones';
import { LIGAMENTS } from '../../../src/data/fitness/anatomy/ligaments';
const all = [...MUSCLES, ...TENDONS, ...NERVES, ...JOINTS, ...BONES, ...LIGAMENTS] as Array<{ id: string; kind: string; nameEn: string; legacyId?: string }>;
const byKind: Record<string, string[]> = {};
for (const s of all) (byKind[s.kind] ??= []).push((s.kind !== 'muscle' ? s.id + ': ' : '') + s.nameEn + ' [' + (s.legacyId ?? '-') + ']');
for (const k of ['tendon', 'nerve', 'joint', 'bone', 'ligament']) console.log('== ' + k + ' (' + byKind[k].length + ') ==\n' + byKind[k].join('\n'));
console.log('== muscle names ==\n' + byKind['muscle'].map((m) => m.split(' [')[0]).join(' | '));
